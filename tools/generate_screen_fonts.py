"""Generate XORA Screen Bitmap ASCII strikes from vendored Terminus 4.49.1 BDFs.

No network, rasterizer, scaling or runtime allocation is required.
"""
from pathlib import Path
import argparse
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "application/Resources/fonts/terminus"
OUTPUT = ROOT / "application/Src/display/drivers/st7789/screen_font_data.inc"
STRIKES = (("small", "ter-u12n.bdf", 6, 12),
           ("body", "ter-u14n.bdf", 8, 14),
           ("title", "ter-u16b.bdf", 8, 16),
           ("large", "ter-u24b.bdf", 12, 24))


def read_strike(path, width, height):
    source = path.read_text(encoding="ascii")
    glyphs = {}
    for block in re.findall(r"STARTCHAR .*?\n(.*?)ENDCHAR", source, re.S):
        code = int(re.search(r"^ENCODING (\d+)$", block, re.M)[1])
        if not 32 <= code <= 126:
            continue
        box = tuple(map(int, re.search(r"^BBX (.*)$", block, re.M)[1].split()))
        advance = int(re.search(r"^DWIDTH (\d+) 0$", block, re.M)[1])
        assert box[:2] == (width, height) and box[2] == 0 and advance == width
        rows = block.split("BITMAP\n", 1)[1].split()
        assert len(rows) == height
        raw = bytes.fromhex("".join(rows))
        assert len(raw) == height * ((width + 7) // 8)
        glyphs[code] = raw
    assert set(glyphs) == set(range(32, 127))
    return glyphs


def generate():
    lines = ["/* Generated by tools/generate_screen_fonts.py; do not edit.",
             " * XORA Screen Bitmap: ASCII subset of Terminus 4.49.1.",
             " * Copyright (C) 2020 Dimitar Toshkov Zhekov. SIL OFL 1.1.",
             " * License: application/Resources/fonts/terminus/OFL.TXT",
             " * Native BDF rows, MSB first; no resampling.", " */", ""]
    for name, filename, width, height in STRIKES:
        path = SOURCE / filename
        glyphs = read_strike(path, width, height)
        lines += [f"/* {filename} SHA-256: {hashlib.sha256(path.read_bytes()).hexdigest()} */",
                  f"static const uint8_t screen_font_{name}[95][{len(glyphs[32])}]",
                  '__attribute__((section(".screen_fonts"), aligned(4))) = {']
        for code, data in sorted(glyphs.items()):
            lines.append("    {" + ",".join(f"0x{byte:02x}" for byte in data) + f"}}, /* U+{code:04X} */")
        lines += ["};", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if OUTPUT.read_text(encoding="ascii") != expected:
            raise SystemExit("Screen font data is stale; run tools/generate_screen_fonts.py")
        print("PASS: all 380 native ASCII glyphs match the vendored BDF sources")
    else:
        OUTPUT.write_text(expected, encoding="ascii", newline="\n")
        print(f"Generated {OUTPUT}")
