"""Convert the pinned official Sarasa Mono SC Regular/Bold TTFs to web subsets.

Requires fonttools[woff]. Usage: python scripts/prepare-sarasa-webfont.py TTF_DIR
The release archive and OFL license provenance are recorded beside the output.
"""
import argparse
import hashlib
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


def unicode_ranges(points):
    ranges = []
    for point in sorted(points):
        if ranges and point == ranges[-1][1] + 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in ranges)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--only', nargs='+', choices=['latin', 'cjk-common', 'cjk-other', 'punctuation', 'symbols'],
                        help='Regenerate only these groups; validate and reuse all other existing subsets.')
    args = parser.parse_args()
    output = Path(__file__).resolve().parents[1] / 'public/fonts/sarasa-mono-sc'
    output.mkdir(parents=True, exist_ok=True)
    # GB2312 level-one Han characters, independent of the website's current copy.
    common = set()
    for lead in range(0xB0, 0xD8):
        for trail in range(0xA1, 0xFF):
            try:
                common.add(ord(bytes([lead, trail]).decode('gb2312')))
            except UnicodeDecodeError:
                pass
    css = ['/* Generated by scripts/prepare-sarasa-webfont.py; see README.md and OFL.txt. */']
    manifest = []
    for style, weight in [('Regular', 400), ('Bold', 700)]:
        source = args.source / f'SarasaMonoSC-{style}.ttf'
        original = TTFont(source)
        points = set(original.getBestCmap())
        latin = {p for p in points if p <= 0x2FFF}
        han = {p for p in points if 0x3400 <= p <= 0x9FFF or 0x20000 <= p <= 0x323AF}
        punctuation = {p for p in points if 0x3000 <= p <= 0x303F or 0xFF00 <= p <= 0xFFEF}
        groups = {'latin': latin, 'cjk-common': han & common,
                  'cjk-other': han - common, 'punctuation': punctuation,
                  'symbols': points - latin - han - punctuation}
        recovered = set()
        for group, chars in groups.items():
            filename = f'sarasa-mono-sc-v1.0.42-{style.lower()}-{group}.woff2'
            target = output / filename
            if args.only is None or group in args.only:
                font = TTFont(source)
                options = subset.Options()
                options.flavor = 'woff2'
                options.layout_features = ['*']
                options.name_IDs = ['*']
                options.name_legacy = True
                options.name_languages = ['*']
                subsetter = subset.Subsetter(options=options)
                subsetter.populate(unicodes=chars)
                subsetter.subset(font)
                font.flavor = 'woff2'
                font.save(target)
            result = TTFont(target)
            assert set(result.getBestCmap()) == chars, f'Lost characters in {filename}'
            for point, glyph in result.getBestCmap().items():
                source_glyph = original.getBestCmap()[point]
                assert result['hmtx'][glyph][0] == original['hmtx'][source_glyph][0]
            recovered.update(result.getBestCmap())
            manifest.append({'file': filename, 'characters': len(chars), 'bytes': target.stat().st_size,
                             'sha256': hashlib.sha256(target.read_bytes()).hexdigest()})
            css.append(f'''@font-face {{
  font-family: 'Sarasa Mono SC';
  src: url('/fonts/sarasa-mono-sc/{filename}') format('woff2');
  font-weight: {weight};
  font-style: normal;
  font-display: swap;
  unicode-range: {unicode_ranges(chars)};
}}''')
            print(f'{filename}: {target.stat().st_size:,} bytes, {len(chars):,} characters', flush=True)
        assert recovered == points, 'Incomplete source character coverage'
        cmap = original.getBestCmap()
        latin_widths = {original['hmtx'][cmap[ord(c)]][0] for c in 'iWM0123456789'}
        assert len(latin_widths) == 1
        width = latin_widths.pop()
        assert all(original['hmtx'][cmap[ord(c)]][0] == width * 2 for c in '中文测试')
    (output / 'fonts.css').write_text('\n\n'.join(css) + '\n', encoding='utf-8')
    (output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
