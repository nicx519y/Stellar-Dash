"""Build only the glyphs used by the LCD's checked-in Chinese catalog.

Normal generation uses the committed subset TTFs. --source-dir additionally
refreshes those subsets from Sarasa Mono SC Regular/Bold under that directory.
No hardware or network operations.
"""
from pathlib import Path
import argparse
import hashlib
import json
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "application/Resources/fonts/chinese"
OUTPUT = ROOT / "application/Src/display/drivers/st7789/screen_chinese_data.inc"
STRIKES = ((12, 12, "Regular"), (16, 14, "Regular"), (16, 16, "Bold"), (24, 24, "Bold"))
# Fixed pen baselines measured from the complete monochrome subset, including
# punctuation. 24px outlines need 26 rows with descenders; use native 23px
# outlines in the unchanged 24px cell instead of clipping or resampling them.
FONT_PIXELS = {12: 12, 14: 14, 16: 16, 24: 23}
BASELINES = {12: 11, 14: 12, 16: 14, 24: 21}


def load_font(height, weight):
    return ImageFont.truetype(str(SOURCE / f"XoraScreenSC-{weight}.ttf"), FONT_PIXELS[height])

def catalog():
    return json.loads((SOURCE / "screen_zh.json").read_text(encoding="utf-8"))

def characters():
    return sorted({ord(c) for value in [*catalog().values(), "简体中文", "Language / 语言"] for c in value if ord(c) > 127})

def prepare(directory):
    from fontTools import subset
    for weight in ("Regular", "Bold"):
        font = subset.load_font(str(directory / f"SarasaMonoSC-{weight}.ttf"), subset.Options())
        missing = set(characters()) - set(font.getBestCmap())
        assert not missing, f"Source font missing characters: {sorted(missing)}"
        sub = subset.Subsetter(); sub.populate(unicodes=characters()); sub.subset(font)
        font.save(SOURCE / f"XoraScreenSC-{weight}.ttf")

def raster(font, codepoint, width, height):
    # Render with padding first: textbbox's outline bounds can differ from the
    # hinted monochrome pixels. Never silently crop pixels at the cell edge.
    pad = height
    image = Image.new("1", (width + 2 * pad, height + 2 * pad))
    draw = ImageDraw.Draw(image)
    x = (width - round(font.getlength(chr(codepoint)))) // 2
    draw.text((pad + x, pad + BASELINES[height]), chr(codepoint), font=font, fill=1, anchor="ls")
    box = image.getbbox()
    if not box or not (pad <= box[0] < box[2] <= pad + width and pad <= box[1] < box[3] <= pad + height):
        raise ValueError(f"Glyph U+{codepoint:04X} does not fit {width}x{height}: {box}")
    return image.crop((pad, pad, pad + width, pad + height)).tobytes()

def generate():
    chars = characters(); entries = catalog()
    lines = ["/* Generated by tools/generate_screen_chinese.py; subset only. */",
             '#define SCREEN_CJK_COUNT %du' % len(chars),
             '#define SCREEN_CATALOG_COUNT %du' % len(entries),
             '#define SCREEN_DATA __attribute__((section(".screen_fonts"), aligned(4)))']
    lines += ['static const uint16_t screen_cjk_codes[] SCREEN_DATA = {',
              ','.join(hex(c) for c in chars), '};']
    for width, height, weight in STRIKES:
        path = SOURCE / f"XoraScreenSC-{weight}.ttf"
        font = load_font(height, weight)
        data = [raster(font, c, width, height) for c in chars]
        lines += [f'/* {path.name} SHA256 {hashlib.sha256(path.read_bytes()).hexdigest()} */',
                  f'static const uint8_t screen_cjk_{height}[SCREEN_CJK_COUNT][{len(data[0])}] SCREEN_DATA = {{']
        lines += ['{' + ','.join(str(b) for b in row) + '},' for row in data]
        lines += ['};']
    blob = bytearray(); offsets = []
    for en, zh in sorted(entries.items()):
        start = len(blob); blob += en.encode() + b'\0'
        target = len(blob); blob += zh.encode() + b'\0'
        offsets.append((start, target))
    assert len(blob) < 65536
    lines += ['static const uint8_t screen_catalog_blob[] SCREEN_DATA = {',
              ','.join(str(b) for b in blob), '};',
              'static const uint16_t screen_catalog_offsets[][2] SCREEN_DATA = {',
              ','.join('{%d,%d}' % pair for pair in offsets), '};', '#undef SCREEN_DATA', '']
    size = len(chars)*(2+sum(((w+7)//8)*h for w,h,_ in STRIKES))+len(blob)+len(offsets)*4
    return '\n'.join(lines), size

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.source_dir: prepare(args.source_dir)
    source, size = generate()
    if args.check: assert OUTPUT.read_text(encoding='ascii') == source, 'Regenerate LCD Chinese data'
    else: OUTPUT.write_text(source, encoding='ascii', newline='\n')
    print(f'{len(catalog())} translations, {len(characters())} glyphs in 4 sizes; {size} bytes plus alignment')
