"""Generate the XORA sidebar's native 28px connection icons from geometry.

Writes SVG masters, opaque theme PNGs and RGB565LE resources. No firmware or
hardware operations. The SVG and bitmap exports share the same geometry.
"""
from pathlib import Path
import argparse
import math
from PIL import Image

try:
    from .assets_fix import _convert_rgb888_to_rgb565le_bytes
except ImportError:
    from assets_fix import _convert_rgb888_to_rgb565le_bytes

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "application/assets"
ICONS = ASSETS / "sysicons"
SIZE = 28
SAMPLES = 8
STROKE = 2.0


def geometry(name):
    if name == "wireless":
        # Three fixed arcs denote wireless mode, not measured signal strength.
        return [("arc", 14, 22, radius, -133, -47) for radius in (16, 11, 6)] + [
            ("dot", 14, 22, 1.5)]
    if name == "USB":
        # Standard USB trident: distinct circle, square and arrow terminals.
        return [("line", 14, 23, 14, 6),
                ("polygon", (10.5, 6), (14, 2), (17.5, 6)),
                ("line", 14, 19, 7, 15),
                ("line", 7, 15, 7, 10),
                ("dot", 7, 9, 2),
                ("line", 14, 15, 21, 11),
                ("line", 21, 11, 21, 7),
                ("box", 20, 5, 2, 2, 0),
                ("dot", 14, 23, 2)]
    raise ValueError(name)


def point(cx, cy, radius, angle):
    angle = math.radians(angle)
    return cx + radius * math.cos(angle), cy + radius * math.sin(angle)


def covered(shape, x, y):
    kind, *args = shape
    if kind == "polygon":
        # Convex filled polygon; sample coverage matches the SVG master.
        crosses = [(bx-ax)*(y-ay)-(by-ay)*(x-ax)
                   for (ax, ay), (bx, by) in zip(args, args[1:]+args[:1])]
        return all(c >= 0 for c in crosses) or all(c <= 0 for c in crosses)
    if kind == "dot":
        cx, cy, radius = args
        return math.hypot(x-cx, y-cy) <= radius
    if kind == "arc":
        cx, cy, radius, first, last = args
        angle = math.degrees(math.atan2(y-cy, x-cx))
        if first <= angle <= last:
            distance = abs(math.hypot(x-cx, y-cy) - radius)
        else:
            distance = min(math.hypot(x-px, y-py) for px, py in
                           (point(cx, cy, radius, first), point(cx, cy, radius, last)))
        return distance <= STROKE / 2
    if kind == "box":
        left, top, width, height, radius = args
        dx = abs(x-left-width/2) - (width/2-radius)
        dy = abs(y-top-height/2) - (height/2-radius)
        distance = math.hypot(max(dx, 0), max(dy, 0)) + min(max(dx, dy), 0) - radius
        return abs(distance) <= STROKE / 2
    x1, y1, x2, y2 = args
    dx, dy = x2-x1, y2-y1
    t = max(0, min(1, ((x-x1)*dx + (y-y1)*dy)/(dx*dx+dy*dy)))
    return math.hypot(x-x1-t*dx, y-y1-t*dy) <= STROKE / 2


def mask(name):
    shapes = geometry(name)
    pixels = []
    for y in range(SIZE):
        for x in range(SIZE):
            count = sum(any(covered(shape, x+(sx+.5)/SAMPLES, y+(sy+.5)/SAMPLES)
                            for shape in shapes)
                        for sy in range(SAMPLES) for sx in range(SAMPLES))
            pixels.append(round(255*count/(SAMPLES*SAMPLES)))
    return bytes(pixels)


def svg(name):
    parts = ['<svg xmlns="http://www.w3.org/2000/svg" width="28" height="28" viewBox="0 0 28 28">',
             '  <!-- Generated by tools/generate_connection_icons.py. XORA connection mode icon. -->',
             '  <g fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">']
    for kind, *args in geometry(name):
        if kind == "polygon":
            points = " ".join(f"{x},{y}" for x, y in args)
            parts.append(f'    <polygon points="{points}" fill="currentColor" stroke="none"/>')
        elif kind == "arc":
            cx, cy, radius, first, last = args
            x1, y1 = point(cx, cy, radius, first)
            x2, y2 = point(cx, cy, radius, last)
            parts.append(f'    <path d="M {x1:.6f} {y1:.6f} A {radius} {radius} 0 0 1 {x2:.6f} {y2:.6f}"/>')
        elif kind == "dot":
            cx, cy, radius = args
            parts.append(f'    <circle cx="{cx}" cy="{cy}" r="{radius}" fill="currentColor" stroke="none"/>')
        elif kind == "box":
            x, y, w, h, r = args
            parts.append(f'    <rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}"/>')
        else:
            x1, y1, x2, y2 = args
            parts.append(f'    <path d="M {x1} {y1} L {x2} {y2}"/>')
    return "\n".join(parts + ['  </g>', '</svg>', ''])


def generate(check=False):
    for name in ("wireless", "USB"):
        source = ICONS / f"{name}.svg"
        expected = svg(name)
        if check:
            assert source.read_text(encoding="utf-8") == expected, source
        else:
            source.write_text(expected, encoding="utf-8", newline="\n")
        coverage = mask(name)
        for theme in ("dark", "light"):
            values = coverage if theme == "dark" else bytes(255-v for v in coverage)
            image = Image.frombytes("L", (SIZE, SIZE), values).convert("RGB")
            png = ICONS / f"{name}_{theme}.png"
            if check:
                with Image.open(png) as actual:
                    assert actual.mode == "RGB" and actual.size == (SIZE, SIZE), png
                    assert actual.tobytes() == image.tobytes(), png
            else:
                image.save(png)
            raw = _convert_rgb888_to_rgb565le_bytes(image.tobytes(), SIZE, SIZE)
            # Keep the tracked legacy mirror consistent with the packaged source.
            for directory in (ICONS, ASSETS):
                path = directory / f"{name}_{theme}_{SIZE}x{SIZE}.rgb565"
                if check:
                    assert path.read_bytes() == raw, path
                else:
                    path.write_bytes(raw)
    print("PASS: connection icon SVG, PNG and RGB565 exports agree" if check else
          "Generated wireless and USB icons in both themes (28x28, RGB565LE)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    generate(parser.parse_args().check)
