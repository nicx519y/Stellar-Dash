#!/usr/bin/env python3
"""Generate checked-in WebHID command tables; --check never writes files."""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "tools/webhid_command_manifest.json"
OUTPUTS = (
    ROOT / "common/webhid_command_policy.generated.h",
    ROOT / "application/www/lib/device-transport/generated-command-policy.ts",
)
TABLES = {
    "config.read": ("configRead", "CONFIG_READ_COMMANDS"),
    "config.write": ("configWrite", "CONFIG_WRITE_COMMANDS"),
    "monitor.read": ("monitorRead", "MONITOR_READ_COMMANDS"),
    "device.control": ("deviceControl", "DEVICE_CONTROL_COMMANDS"),
    "firmware.update": ("firmwareUpdate", "FIRMWARE_UPDATE_COMMANDS"),
}
# These names have explicit retirement/bootstrap handling in the dispatcher.
INLINE_READ_COMMANDS = {"ping", "get_device_auth"}


def command_groups(manifest: dict) -> dict[str, list[str]]:
    """Reject ambiguous policy instead of generating a permissive fallback."""
    groups: dict[str, list[str]] = {}
    seen: set[str] = set()
    migrations: Counter[str] = Counter()
    for group in manifest["groups"]:
        scope = group["scope"]
        if scope not in TABLES or scope in groups:
            raise ValueError(f"Unknown or repeated scope: {scope}")
        groups[scope] = []
        for command in group["commands"]:
            name = command["name"]
            if not isinstance(name, str) or not re.fullmatch(r"[a-z][a-z0-9_.-]*", name):
                raise ValueError(f"Invalid command name: {name!r}")
            if name in seen:
                raise ValueError(f"Repeated command: {name}")
            seen.add(name)
            groups[scope].append(name)
            migrations[command["migration"]] += 1
    if set(groups) != set(TABLES):
        raise ValueError("The manifest must declare every supported scope")
    if len(seen) != manifest["commandCount"]:
        raise ValueError("commandCount does not match the manifest")
    if dict(migrations) != manifest["migrationStatusCounts"]:
        raise ValueError("migrationStatusCounts does not match the manifest")
    if not INLINE_READ_COMMANDS <= set(groups["config.read"]):
        raise ValueError("Inline bootstrap/retired commands must retain config.read")
    for command in manifest.get("serviceCommands", []):
        name, scope = command["name"], command["scope"]
        if scope not in groups or not isinstance(name, str) or not re.fullmatch(r"[a-z][a-z0-9_.-]*", name):
            raise ValueError(f"Invalid service command: {command!r}")
        if name in seen:
            raise ValueError(f"Repeated command: {name}")
        seen.add(name)
        groups[scope].append(name)
    return groups


def render(manifest: dict) -> tuple[str, str]:
    groups = command_groups(manifest)
    notice = "Generated by tools/generate_webhid_command_policy.py. Do not edit."
    cpp = [f"/* {notice} */", "#ifndef XORA_WEBHID_COMMAND_POLICY_GENERATED_H",
           "#define XORA_WEBHID_COMMAND_POLICY_GENERATED_H", ""]
    ts = [f"// {notice}", ""]
    for scope, (cpp_name, ts_name) in TABLES.items():
        cpp.append(f"static const char *const {cpp_name}[] = {{")
        cpp.extend(f'    "{name}",' for name in groups[scope] if name not in INLINE_READ_COMMANDS)
        cpp.extend(["};", ""])
        ts.append(f"export const {ts_name}: readonly string[] = [")
        ts.extend(f"  '{name}'," for name in groups[scope])
        ts.extend(["] as const;", ""])
    cpp.extend(["#endif", ""])
    return "\n".join(cpp), "\n".join(ts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if checked-in tables are stale")
    args = parser.parse_args(argv)
    try:
        results = render(json.loads(MANIFEST.read_text(encoding="utf-8")))
    except (KeyError, TypeError, ValueError) as error:
        parser.error(str(error))
    stale = []
    for path, content in zip(OUTPUTS, results):
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("Stale WebHID policy: " + ", ".join(stale))
        print("Run python tools/generate_webhid_command_policy.py")
        return 1
    print("WebHID command policy " + ("is current" if args.check else "generated"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
