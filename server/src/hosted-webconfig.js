'use strict';

const fs = require('fs');
const crypto = require('crypto');
const path = require('path');
const express = require('express');
const { buildContentSecurityPolicy } = require('./http-security');

const HOSTED_WEB_CONFIG_ROUTES = Object.freeze([
    'global',
    'keys',
    'lighting',
    'buttons-performance',
    'switch-marking',
    'firmware',
    'view-logs'
]);

function parseBoolean(value, defaultValue = false) {
    if (value === undefined || value === null || value === '') {
        return defaultValue;
    }
    return /^(1|true|yes|on)$/i.test(String(value));
}

function resolveHostedWebConfigOptions(environment = process.env,
                                       serverRoot = path.join(__dirname, '..')) {
    const staticDir = path.resolve(
        environment.WEB_CONFIG_STATIC_DIR ||
        path.join(serverRoot, 'webconfig')
    );
    return {
        staticDir,
        required: parseBoolean(environment.WEB_CONFIG_REQUIRE_STATIC, false)
    };
}

function inlineScriptHashes(html) {
    if (typeof html !== 'string') {
        throw new TypeError('HTML source must be a string');
    }
    const hashes = [];
    const scriptPattern = /<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi;
    let match;
    while ((match = scriptPattern.exec(html)) !== null) {
        if (/\bsrc\s*=/i.test(match[1])) {
            continue;
        }
        const digest = crypto.createHash('sha256')
            .update(match[2], 'utf8')
            .digest('base64');
        hashes.push(`sha256-${digest}`);
    }
    return [...new Set(hashes)];
}

function htmlSecurityPolicy(filePath) {
    const html = fs.readFileSync(filePath, 'utf8');
    return buildContentSecurityPolicy({
        scriptHashes: inlineScriptHashes(html)
    });
}

function setHostedFileHeaders(response, filePath) {
    const normalized = filePath.replaceAll('\\', '/');
    if (normalized.endsWith('.html')) {
        response.set('Cache-Control', 'no-cache, no-store');
        /*
         * Next static exports contain small inline bootstrap scripts. Hash the
         * exact generated bytes instead of weakening script-src.
         */
        response.set(
            'Content-Security-Policy',
            htmlSecurityPolicy(filePath)
        );
    } else if (normalized.includes('/_next/static/')) {
        response.set(
            'Cache-Control',
            'public, max-age=31536000, immutable'
        );
    } else {
        response.set('Cache-Control', 'public, max-age=3600');
    }
}

function installHostedWebConfig(app, options) {
    if (!app || !options || typeof options.staticDir !== 'string') {
        throw new TypeError('hosted WebConfig options are required');
    }

    const staticDir = path.resolve(options.staticDir);
    const profileSlugs = Array.isArray(options.profileSlugs)
        ? [...new Set(options.profileSlugs)]
        : [];
    if (profileSlugs.some(profile =>
        typeof profile !== 'string' ||
        !/^[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?$/.test(profile))) {
        throw new TypeError('hosted WebConfig profile slugs are invalid');
    }
    const indexPath = path.join(staticDir, 'index.html');
    const indexAvailable = fs.existsSync(indexPath) &&
        fs.statSync(indexPath).isFile();
    const nextStaticPath = path.join(staticDir, '_next', 'static');
    const assetsAvailable = fs.existsSync(nextStaticPath) &&
        fs.statSync(nextStaticPath).isDirectory();
    const available = indexAvailable && assetsAvailable;

    if (!available) {
        if (options.required) {
            if (indexAvailable) {
                throw new Error(
                    `hosted WebConfig assets are missing: ${nextStaticPath}`
                );
            }
            throw new Error(
                `hosted WebConfig index is missing: ${indexPath}`
            );
        }
        return {
            enabled: false,
            staticDir
        };
    }

    app.use(express.static(staticDir, {
        dotfiles: 'deny',
        etag: true,
        fallthrough: true,
        index: ['index.html'],
        redirect: true,
        setHeaders(response, filePath) {
            setHostedFileHeaders(response, filePath);
        }
    }));

    /*
     * The normal export contains one directory per route. Keep a narrow SPA
     * fallback as a deployment compatibility net, but never turn unknown API,
     * download or asset paths into HTML responses.
     */
    const settingsRoute = `(?:${HOSTED_WEB_CONFIG_ROUTES.join('|')})`;
    const profileRoute = profileSlugs.length > 0
        ? `|/webconfig/(?:${profileSlugs.join('|')})/${settingsRoute}`
        : '';
    const routePattern = new RegExp(
        `^(?:/${settingsRoute}${profileRoute})/?$`
    );
    app.get(routePattern, (request, response, next) => {
        setHostedFileHeaders(response, indexPath);
        response.sendFile(indexPath, error => {
            if (error) {
                next(error);
            }
        });
    });

    return {
        enabled: true,
        staticDir
    };
}

module.exports = {
    HOSTED_WEB_CONFIG_ROUTES,
    htmlSecurityPolicy,
    inlineScriptHashes,
    installHostedWebConfig,
    parseBoolean,
    resolveHostedWebConfigOptions
};
