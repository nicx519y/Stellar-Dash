'use strict';

const fs = require('fs');
const crypto = require('crypto');
const path = require('path');
const express = require('express');
const { buildContentSecurityPolicy } = require('./http-security');

function parseBoolean(value, defaultValue = false) {
    if (value === undefined || value === null || value === '') {
        return defaultValue;
    }
    return /^(1|true|yes|on)$/i.test(String(value));
}

function resolveHostedWebConfigOptions(environment = process.env,
                                       serverRoot = path.join(__dirname, '..')) {
    const staticDir = path.resolve(
        environment.WEB_CONFIG_STATIC_DIR ||
        path.join(serverRoot, 'webconfig')
    );
    return {
        staticDir,
        required: parseBoolean(environment.WEB_CONFIG_REQUIRE_STATIC, false)
    };
}

function inlineScriptHashes(html) {
    if (typeof html !== 'string') {
        throw new TypeError('HTML source must be a string');
    }
    const hashes = [];
    const scriptPattern = /<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi;
    let match;
    while ((match = scriptPattern.exec(html)) !== null) {
        if (/\bsrc\s*=/i.test(match[1])) {
            continue;
        }
        const digest = crypto.createHash('sha256')
            .update(match[2], 'utf8')
            .digest('base64');
        hashes.push(`sha256-${digest}`);
    }
    return [...new Set(hashes)];
}

function htmlSecurityPolicy(filePath) {
    const html = fs.readFileSync(filePath, 'utf8');
    return buildContentSecurityPolicy({
        scriptHashes: inlineScriptHashes(html)
    });
}

function installHostedWebConfig(app, options) {
    if (!app || !options || typeof options.staticDir !== 'string') {
        throw new TypeError('hosted WebConfig options are required');
    }

    const staticDir = path.resolve(options.staticDir);
    const indexPath = path.join(staticDir, 'index.html');
    const available = fs.existsSync(indexPath) &&
        fs.statSync(indexPath).isFile();

    if (!available) {
        if (options.required) {
            throw new Error(
                `hosted WebConfig index is missing: ${indexPath}`
            );
        }
        return {
            enabled: false,
            staticDir
        };
    }

    app.use(express.static(staticDir, {
        dotfiles: 'deny',
        etag: true,
        fallthrough: true,
        index: ['index.html'],
        redirect: true,
        setHeaders(response, filePath) {
            const normalized = filePath.replaceAll('\\', '/');
            if (normalized.endsWith('.html')) {
                response.set('Cache-Control', 'no-cache, no-store');
                /*
                 * Next static exports contain small inline bootstrap scripts.
                 * Hash the exact generated bytes instead of weakening
                 * script-src with unsafe-inline.
                 */
                response.set(
                    'Content-Security-Policy',
                    htmlSecurityPolicy(filePath)
                );
            } else if (normalized.includes('/_next/static/')) {
                response.set(
                    'Cache-Control',
                    'public, max-age=31536000, immutable'
                );
            } else {
                response.set('Cache-Control', 'public, max-age=3600');
            }
        }
    }));

    return {
        enabled: true,
        staticDir
    };
}

module.exports = {
    htmlSecurityPolicy,
    inlineScriptHashes,
    installHostedWebConfig,
    parseBoolean,
    resolveHostedWebConfigOptions
};
