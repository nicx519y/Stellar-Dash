"""Fit a monotone operational SOC curve from two ordered discharge exports.

Assumes equal, constant current/temperature and negligible inter-run recharge.
Uses five-minute voltage range midpoints, not raw gauge SOC as ground truth.
No device access; writes only the explicitly selected header and audit report.
"""
import argparse
import hashlib
import json
from pathlib import Path


def monotone_voltage(points):
    blocks = []
    for i, (_, mv) in enumerate(points):
        blocks.append([i, i, float(mv), 1])
        while len(blocks) > 1 and blocks[-2][2] < blocks[-1][2]:
            b, a = blocks.pop(), blocks.pop()
            n = a[3] + b[3]
            blocks.append([a[0], b[1], (a[2]*a[3]+b[2]*b[3])/n, n])
    result = list(points)
    for first, last, value, _ in blocks:
        for i in range(first, last+1):
            result[i] = (points[i][0], value)
    return result


def interpolate(points, x):
    if x <= points[0][0]:
        return points[0][1]
    for (a, va), (b, vb) in zip(points, points[1:]):
        if x <= b:
            return va + (vb-va)*(x-a)/(b-a)
    return points[-1][1]


def fit(paths):
    points, audit, elapsed = [], [], 0
    for index, path in enumerate(paths):
        raw = path.read_bytes()
        data = json.loads(raw.decode('utf-8-sig'))
        source = next(s for s in data['sources'] if s['source'] == 'battery')
        rows = sorted(source['items'], key=lambda r: r['sequence'])
        start = next(r for r in rows if r['event'] == 101)
        end = next(r for r in rows if r['event'] == (114 if index == 0 else 108))
        assert end['boot'] == start['boot'] and end['uptimeMs'] > start['uptimeMs']
        if index == 0:
            assert end['data'][2] == 2, 'First run must end manually'
            points.append((0, start['data'][4]))
        segment = [r for r in rows if start['sequence'] <= r['sequence'] <= end['sequence']]
        assert not any(r['event'] == 103 for r in segment), 'Configuration changed'
        assert not any(r['event'] == 110 and r['data'][2] & 1 for r in segment), 'USB during discharge'
        assert all(b['sequence'] == a['sequence']+1 for a,b in zip(segment,segment[1:])), 'Missing records'
        summaries = [r for r in segment if r['event'] == 102 and
                     r['data'][2] >= start['uptimeMs'] and r['data'][3] <= end['uptimeMs']]
        assert summaries and all(r['data'][8] and not r['data'][9] and not r['data'][13]
                                 for r in summaries), 'Invalid discharge buckets'
        for r in summaries:
            d = r['data']
            points.append((elapsed+(d[2]+d[3])/2-start['uptimeMs'], (d[4]+d[5])/2))
        duration = end['uptimeMs']-start['uptimeMs']
        audit.append(dict(file=path.name, sha256=hashlib.sha256(raw).hexdigest(),
                          export_complete=data['complete'], source_status=source['status'],
                          start_sequence=start['sequence'], end_sequence=end['sequence'],
                          duration_ms=duration, accepted_buckets=len(summaries),
                          config=next(r['data'][2:] for r in rows if r['event']==100)))
        elapsed += duration
    assert audit[0]['config'] == audit[1]['config'], 'Configurations differ'
    # Operational empty is the existing 3.20V cutoff, not chemical zero capacity.
    points.append((elapsed, 3200))
    fitted = monotone_voltage(points)
    levels = [0, 10, 20, 50] + list(range(100, 1001, 50))
    knots = [(round(interpolate(fitted, elapsed*(1-soc/1000))), soc) for soc in levels]
    assert all(a[0] < b[0] for a,b in zip(knots,knots[1:]))
    errors = [abs(interpolate(knots, mv) - 1000*(1-t/elapsed))/10 for t,mv in points]
    report = dict(version='20261025', assumptions=['constant equal current and temperature',
                  'negligible inter-run recharge', 'first observed loaded voltage normalized to 100%'],
                  voltage_method='midpoint of each min/max summary, equal-weight isotonic voltage vs time',
                  runs=audit, observed_duration_ms=elapsed, knots_mv_permille=knots,
                  training_mae_percentage_points=sum(errors)/len(errors),
                  training_max_error_percentage_points=max(errors),
                  samples=[dict(time_ms=t, voltage_mv=v, reference_permille=1000*(1-t/elapsed)) for t,v in points])
    return knots, report


def header(knots):
    rows = '\n'.join(f'        {{{mv}u, {soc}u}},' for mv,soc in knots)
    return '''#pragma once
#include <stdint.h>

// Generated by tools/fit_battery_soc.py; audit: docs/data/battery-soc-20261025.json.
// Constant-load operational capacity, negligible recharge between the two runs.
// Raw MAX17048 SOC remains diagnostic only. Protection always uses raw voltage.
__attribute__((optimize("Os"))) inline uint16_t BatterySoc_FromMillivolts(uint16_t mv) {
    static constexpr uint16_t curve[][2] = {
''' + rows + '''
    };
    if (mv <= curve[0][0]) return 0u;
    for (unsigned i=1; i<sizeof(curve)/sizeof(curve[0]); ++i) {
        if (mv <= curve[i][0]) {
            const uint32_t width = curve[i][0]-curve[i-1][0];
            return uint16_t(curve[i-1][1] +
                ((uint32_t(mv)-curve[i-1][0])*(curve[i][1]-curve[i-1][1])+width/2u)/width);
        }
    }
    return 1000u;
}
'''


def typescript(knots):
    rows = '\n'.join(f'  [{mv}, {soc}],' for mv,soc in knots)
    return '''// Generated by tools/fit_battery_soc.py; same curve as STM32 firmware.
const curve: ReadonlyArray<readonly [number, number]> = [
''' + rows + '''
];

export function batterySocPermille(mv: number): number {
  if (!Number.isFinite(mv) || mv <= curve[0][0]) return 0;
  for (let i = 1; i < curve.length; i++) {
    if (mv <= curve[i][0]) {
      const [lowMv, lowSoc] = curve[i - 1];
      const [highMv, highSoc] = curve[i];
      return lowSoc + Math.round((mv - lowMv) * (highSoc - lowSoc) / (highMv - lowMv));
    }
  }
  return 1000;
}
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('logs', type=Path, nargs=2, help='first discharge, then second discharge')
    parser.add_argument('--header', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    parser.add_argument('--typescript', type=Path, required=True)
    args = parser.parse_args()
    knots, report = fit(args.logs)
    for path in (args.header, args.report, args.typescript):
        path.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(header(knots), encoding='utf-8')
    args.report.write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8')
    args.typescript.write_text(typescript(knots), encoding='utf-8')
    print(json.dumps({k:v for k,v in report.items() if k!='samples'}, indent=2))
